#!/usr/bin/env node
// Generates Tokens.swift / Icons.swift (iOS) and Tokens.kt / Icons.kt (Android)
// from tokens.json + icons.json.
//
//   node native/design-tokens/generate.mjs          write the files
//   node native/design-tokens/generate.mjs --check  exit 1 if committed output is stale (CI)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const tokens = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));
const icons = JSON.parse(readFileSync(join(here, 'icons.json'), 'utf8'));
const check = process.argv.includes('--check');

const IOS_DIR = join(root, 'ios/FootballPredictions/Core/DesignSystem');
const ANDROID_DIR = join(root, 'android/app/src/main/java/com/maamoun/footballpredictions/core/designsystem');

// ── colour parsing ───────────────────────────────────────────────────────────
function parseColor(value) {
  let m = /^#([0-9a-f]{6})$/i.exec(value);
  if (m) {
    const n = parseInt(m[1], 16);
    return { r: (n >> 16) & 255, g: (n >> 8) & 255, b: n & 255, a: 1 };
  }
  m = /^rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*\)$/i.exec(value);
  if (m) return { r: +m[1], g: +m[2], b: +m[3], a: +m[4] };
  throw new Error(`Unsupported colour: ${value}`);
}
const swiftColor = (v) => {
  const { r, g, b, a } = parseColor(v);
  const f = (n) => (n / 255).toFixed(4).replace(/0+$/, '').replace(/\.$/, '.0');
  return `Color(.sRGB, red: ${f(r)}, green: ${f(g)}, blue: ${f(b)}, opacity: ${a})`;
};
const kotlinColor = (v) => {
  const { r, g, b, a } = parseColor(v);
  const hex = (n) => n.toString(16).toUpperCase().padStart(2, '0');
  return `Color(0x${hex(Math.round(a * 255))}${hex(r)}${hex(g)}${hex(b)})`;
};

const paletteKeys = Object.keys(tokens.palettes.dark);
const BANNER = 'Generated by native/design-tokens/generate.mjs from tokens.json — do not edit.';

// ── Swift ────────────────────────────────────────────────────────────────────
function swiftTokens() {
  const lines = [`// ${BANNER}`, 'import SwiftUI', ''];
  lines.push('struct Palette: Sendable {');
  for (const k of paletteKeys) lines.push(`    let ${k}: Color`);
  lines.push('}', '', 'enum Tokens {');
  for (const mode of ['dark', 'light']) {
    lines.push(`    static let ${mode} = Palette(`);
    lines.push(paletteKeys.map((k) => `        ${k}: ${swiftColor(tokens.palettes[mode][k])}`).join(',\n'));
    lines.push('    )', '');
  }
  lines.push('    enum Fixed {');
  for (const [k, v] of Object.entries(tokens.fixed)) lines.push(`        static let ${k} = ${swiftColor(v)}`);
  lines.push('    }', '');
  for (const [group, name] of [['spacing', 'Spacing'], ['radius', 'Radius'], ['fontSize', 'FontSize']]) {
    lines.push(`    enum ${name} {`);
    for (const [k, v] of Object.entries(tokens[group])) lines.push(`        static let ${k}: CGFloat = ${v}`);
    lines.push('    }', '');
  }
  lines.pop();
  lines.push('}', '');
  return lines.join('\n');
}
function swiftIcons() {
  const lines = [`// ${BANNER}`, '', 'enum AppIcon {'];
  for (const [k, v] of Object.entries(icons)) lines.push(`    static let ${k} = "${v.sf}"`);
  lines.push('}', '');
  return lines.join('\n');
}

// ── Kotlin ───────────────────────────────────────────────────────────────────
const PKG = 'com.maamoun.footballpredictions.core.designsystem';
function kotlinTokens() {
  const lines = [`// ${BANNER}`, `package ${PKG}`, '', 'import androidx.compose.ui.graphics.Color', 'import androidx.compose.ui.unit.dp', 'import androidx.compose.ui.unit.sp', ''];
  lines.push('data class Palette(');
  lines.push(paletteKeys.map((k) => `    val ${k}: Color`).join(',\n'));
  lines.push(')', '', 'object Tokens {');
  for (const mode of ['dark', 'light']) {
    lines.push(`    val ${mode} = Palette(`);
    lines.push(paletteKeys.map((k) => `        ${k} = ${kotlinColor(tokens.palettes[mode][k])}`).join(',\n'));
    lines.push('    )', '');
  }
  lines.push('    object Fixed {');
  for (const [k, v] of Object.entries(tokens.fixed)) lines.push(`        val ${k} = ${kotlinColor(v)}`);
  lines.push('    }', '');
  for (const [group, name, unit] of [['spacing', 'Spacing', 'dp'], ['radius', 'Radius', 'dp'], ['fontSize', 'FontSize', 'sp']]) {
    lines.push(`    object ${name} {`);
    for (const [k, v] of Object.entries(tokens[group])) lines.push(`        val ${k} = ${v}.${unit}`);
    lines.push('    }', '');
  }
  lines.pop();
  lines.push('}', '');
  return lines.join('\n');
}
function kotlinIcons() {
  const lines = [`// ${BANNER}`, `package ${PKG}`, '', 'import androidx.compose.material.icons.Icons', 'import androidx.compose.material.icons.filled.EmojiEvents', 'import androidx.compose.material.icons.filled.Lock', 'import androidx.compose.material.icons.outlined.*', 'import androidx.compose.ui.graphics.vector.ImageVector', '', 'object AppIcon {'];
  for (const [k, v] of Object.entries(icons)) {
    const filled = k === 'lock' || k === 'trophyFilled';
    const ref = filled ? `Icons.Filled.${v.material}` : `Icons.Outlined.${v.material}`;
    lines.push(`    val ${k}: ImageVector get() = ${ref}`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

const outputs = [
  [join(IOS_DIR, 'Tokens.swift'), swiftTokens()],
  [join(IOS_DIR, 'Icons.swift'), swiftIcons()],
  [join(ANDROID_DIR, 'Tokens.kt'), kotlinTokens()],
  [join(ANDROID_DIR, 'Icons.kt'), kotlinIcons()],
];

let stale = false;
for (const [path, content] of outputs) {
  if (check) {
    const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (current !== content) {
      console.error(`STALE: ${path}`);
      stale = true;
    }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${path.replace(root + '/', 'native/')}`);
  }
}
if (check && stale) {
  console.error('Design tokens are out of date. Run: node native/design-tokens/generate.mjs');
  process.exit(1);
}
